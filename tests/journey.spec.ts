test('registro persistido → confirmación → login → diagnóstico; recuperación (Auth simulado)',async({page,request})=>{
 const email=`confirm-${Date.now()}@example.test`;
 await page.goto('/');await page.getByRole('button',{name:'Crear una cuenta',exact:true}).click();
 await page.getByRole('textbox',{name:'Nombre',exact:true}).fill('Perfil pendiente');
 await page.getByLabel('Fecha de nacimiento',{exact:true}).fill('2001-02-03');
 await page.getByRole('button',{name:'Programa de demostración',exact:true}).click();
 await page.getByRole('textbox',{name:'Correo electrónico',exact:true}).fill(email);
 await page.getByRole('textbox',{name:'Contraseña',exact:true}).fill('Prueba123+');
 await page.getByRole('textbox',{name:'Confirmar contraseña',exact:true}).fill('Prueba123+');
 await page.getByRole('checkbox').check();await page.getByRole('button',{name:'Crear cuenta de estudiante',exact:true}).click();
 await expect(page.getByText(/Revisa tu correo y confirma la cuenta/)).toBeVisible();
 const saved=await request.post('http://127.0.0.1:54329/__test/profile',{data:{email}});
 expect(await saved.json()).toMatchObject({name:'Perfil pendiente',birthDate:'2001-02-03',semester:1,program:'demo',complete:true});
 const denied=await request.post('http://127.0.0.1:54329/auth/v1/token?grant_type=password',{data:{email,password:'Prueba123+'}});
 expect(denied.ok()).toBeFalsy();
 const confirmed=await request.post('http://127.0.0.1:54329/__test/confirm',{data:{email}});
 const confirmedSession=await confirmed.json();
 await page.goto(`/#access_token=${confirmedSession.access_token}&refresh_token=${confirmedSession.refresh_token}&type=signup&expires_in=3600&token_type=bearer`);
 await expect(page).not.toHaveURL(/access_token/);
 await page.reload(); // Registration form and the confirmation session are gone.
 await page.getByRole('textbox',{name:'Correo electrónico',exact:true}).fill(email);
 await page.getByRole('textbox',{name:'Contraseña',exact:true}).fill('Prueba123+');
 await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click();
 await expect(page.getByText('Hola, Perfil pendiente',{exact:true})).toBeVisible();
 await expect(page.getByText('Completa tu perfil',{exact:true})).not.toBeVisible();
 await page.getByRole('button',{name:'Conocer mi punto de partida',exact:true}).click();
 await page.getByRole('button',{name:'Preparar diagnóstico',exact:true}).click();
 await page.getByRole('button',{name:'Entiendo las condiciones',exact:true}).click();
 await page.getByRole('button',{name:'Sí, iniciar diagnóstico',exact:true}).click();
 await expect(page.getByText('Pregunta 1 de 7',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Volver al menú',exact:true}).click();
 await page.getByRole('button',{name:'Confirmar salida al menú',exact:true}).click();
 await page.getByRole('button',{name:'Cerrar sesión',exact:true}).click();
 await page.getByRole('button',{name:'Cerrar sesión',exact:true}).last().click();
 await page.getByRole('button',{name:'Olvidé mi contraseña',exact:true}).click();
 await page.getByRole('textbox',{name:'Correo electrónico',exact:true}).fill(email);
 await page.getByRole('button',{name:'Enviar enlace de recuperación',exact:true}).click();
 await expect(page.getByText(/Si existe una cuenta con ese correo/)).toBeVisible();
 // No SMTP: inject a fixture-issued recovery session to exercise SDK URL handling and updateUser.
 const response=await request.post('http://127.0.0.1:54329/auth/v1/token?grant_type=password',{data:{email,password:'Prueba123+'}});
 const session=await response.json();
 await page.goto(`/#access_token=${session.access_token}&refresh_token=${session.refresh_token}&type=recovery&expires_in=3600&token_type=bearer`);
 await expect(page.getByRole('heading',{name:'Nueva contraseña',exact:true})).toBeVisible();
 await page.getByRole('textbox',{name:'Contraseña',exact:true}).fill('Renovada456+');
 await page.getByRole('textbox',{name:'Confirmar contraseña',exact:true}).fill('Renovada456+');
 await page.getByRole('button',{name:'Guardar nueva contraseña',exact:true}).click();
 await expect(page.getByText('Contraseña actualizada. Inicia sesión.',{exact:true})).toBeVisible();
 await page.getByRole('textbox',{name:'Correo electrónico',exact:true}).fill(email);
 await page.getByRole('textbox',{name:'Contraseña',exact:true}).fill('Renovada456+');
 await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click();
 await expect(page.getByText('Hola, Perfil pendiente',{exact:true})).toBeVisible();
});
