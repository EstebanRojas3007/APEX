import {test,expect} from '@playwright/test';
for(const width of [1280,390])test(`docente: login, grupos, búsqueda, detalle, regreso, errores y revocación (${width}px)`,async({page,request})=>{
 const setup=await request.post('http://127.0.0.1:54329/__test/teacher/setup');expect(setup.ok(),await setup.text()).toBeTruthy();const fixture=await setup.json();
 await page.setViewportSize({width,height:900});let authorization='';
 page.on('request',req=>{if(req.url().endsWith('/rpc/apex_api'))authorization=req.headers().authorization??authorization;});
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 const login=async(email:string)=>{
  await page.getByRole('textbox',{name:'Correo electrónico',exact:true}).fill(email);
  await page.getByRole('textbox',{name:'Contraseña',exact:true}).fill('Prueba123+');
  await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click();
 };
 await page.goto('/');await login(fixture.teacher.email);
 await expect(page.getByText(`Bienvenido, profesor ${fixture.teacher.name}`,{exact:true})).toBeVisible();
 await expect(page.getByText('Selecciona tu grupo',{exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:`Abrir grupo ${fixture.otherGroup.code}`,exact:true})).toHaveCount(0);
 await expect(page.getByText('Permisos y asignación docente',{exact:true})).toHaveCount(0);
 await page.screenshot({path:`Docs/evidence/teacher-groups-${width}.png`,fullPage:true});
 await page.getByRole('button',{name:`Abrir grupo ${fixture.group.code}`,exact:true}).click();
 await expect(page.getByText(/1 estudiantes activos/)).toBeVisible();
 await page.getByRole('textbox',{name:'Buscar estudiante'}).fill('ausente');
 await expect(page.getByText('Sin estudiantes que coincidan con la búsqueda.',{exact:true})).toBeVisible();
 await page.getByRole('textbox',{name:'Buscar estudiante'}).fill('asignada');
 await page.getByRole('button',{name:fixture.alice.name,exact:true}).click();
 await page.getByRole('button',{name:`Ver seguimiento de ${fixture.alice.name}`,exact:true}).click();
 await expect(page.getByText('Diagnóstico · pendiente',{exact:true})).toBeVisible();
 await expect(page.getByText('Básico · 0/7 secciones completadas',{exact:true})).toBeVisible();
 await expect(page.getByText(/Último inicio de sesión: Pendiente/)).toBeVisible();
 await page.screenshot({path:`Docs/evidence/teacher-student-${width}.png`,fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.getByRole('button',{name:'Volver al grupo',exact:true}).click();
 await expect(page.getByRole('textbox',{name:'Buscar estudiante'})).toBeVisible();
 await expect(page.getByRole('textbox',{name:'Buscar estudiante'})).toHaveValue('asignada');
 await expect(page.getByRole('button',{name:fixture.alice.name,exact:true})).toHaveAttribute('aria-expanded','true');
 await page.goBack();await expect(page.getByText('Progreso por nivel',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Volver al grupo',exact:true}).click();
 // IDs can be changed in URLs: the server still denies access.
 await page.evaluate(groupId=>{history.pushState(null,'',`#profesor/grupos/${groupId}`);dispatchEvent(new PopStateEvent('popstate'));},fixture.otherGroup.id);
 await expect(page.getByRole('alert').filter({hasText:'Grupo no asignado.'})).toBeVisible();
 await page.getByRole('button',{name:'Reintentar',exact:true}).click();
 await expect(page.getByRole('alert').filter({hasText:'Grupo no asignado.'})).toBeVisible();
 await page.getByRole('button',{name:'Volver a mis grupos',exact:true}).click();
 await page.getByRole('button',{name:`Abrir grupo ${fixture.group.code}`,exact:true}).click();
 await expect(page.getByRole('button',{name:fixture.alice.name,exact:true})).toHaveAttribute('aria-expanded','false');
 await page.getByRole('button',{name:fixture.alice.name,exact:true}).click();
 await page.getByRole('button',{name:`Ver seguimiento de ${fixture.alice.name}`,exact:true}).click();
 const revoked=await request.post('http://127.0.0.1:54329/__test/teacher/revoke',{headers:{Authorization:authorization},data:{groupId:fixture.group.id,studentId:fixture.alice.id}});
 expect(revoked.ok()).toBeTruthy();
 await page.getByRole('button',{name:'Actualizar seguimiento',exact:true}).click();
 await expect(page.getByRole('alert').filter({hasText:'Estudiante no asignado.'})).toBeVisible();
 await expect(page.getByText('Progreso por nivel',{exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'Volver al grupo',exact:true}).click();
 await expect(page.getByText('Este grupo no tiene estudiantes activos disponibles para seguimiento.',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Cerrar sesión',exact:true}).click();await page.getByRole('dialog').getByRole('button',{name:'Cerrar sesión',exact:true}).click();await login(fixture.empty.email);
 await expect(page.getByText('Aún no tienes grupos asignados',{exact:true})).toBeVisible();
 expect(errors).toEqual([]);
});
