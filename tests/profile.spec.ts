 await page.getByRole('button',{name:'Programa de demostración',exact:true}).click();await page.getByRole('button',{name:'Guardar perfil',exact:true}).click();
 await page.getByRole('button',{name:'Mi progreso',exact:true}).click();await expect(page.getByText('Historial',{exact:true})).toBeVisible();
